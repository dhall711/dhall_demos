-- 2) Table definitions
CREATE OR REPLACE TABLE PRODUCTS (
    PRODUCT_ID VARCHAR(20) PRIMARY KEY,
    PRODUCT_NAME VARCHAR(100),
    PRODUCT_CATEGORY VARCHAR(50),
    BASE_PRICE DECIMAL(10,2),
    SERVICE_TYPE VARCHAR(30)
);

CREATE OR REPLACE TABLE PROMOTION_TYPES (
    PROMO_CODE VARCHAR(30) PRIMARY KEY,
    PROMO_NAME VARCHAR(100),
    DISCOUNT_TYPE VARCHAR(20), -- PERCENTAGE, FIXED_AMOUNT, FREE_MONTHS
    DISCOUNT_VALUE DECIMAL(10,2),
    DURATION_MONTHS INTEGER,
    APPLICABLE_PRODUCTS VARCHAR(500)
);

CREATE OR REPLACE TABLE SERVICE_AREAS (
    AREA_ID VARCHAR(20) PRIMARY KEY,
    CITY VARCHAR(100),
    STATE VARCHAR(10),
    REGION VARCHAR(30),
    LAT NUMBER(10,6),
    LON NUMBER(10,6)
);

CREATE OR REPLACE TABLE CUSTOMERS (
    CUSTOMER_ID VARCHAR(15) PRIMARY KEY,
    SERVICE_CITY VARCHAR(100),
    SERVICE_STATE VARCHAR(10),
    SERVICE_REGION VARCHAR(30),
    CUSTOMER_LAT NUMBER(10,6),
    CUSTOMER_LON NUMBER(10,6)
);

CREATE OR REPLACE TABLE ORDER_SYSTEM_DATA (
    ORDER_ID VARCHAR(20) PRIMARY KEY,
    CUSTOMER_ID VARCHAR(15),
    ORDER_DATE DATE,
    PRODUCT_ID VARCHAR(20),
    PROMO_CODE VARCHAR(30),
    BASE_AMOUNT DECIMAL(10,2),
    DISCOUNT_AMOUNT DECIMAL(10,2),
    FINAL_AMOUNT DECIMAL(10,2),
    ORDER_STATUS VARCHAR(20),
    LINE_NUMBER VARCHAR(20),
    ACCOUNT_ID VARCHAR(25),
    PROMO_START_CYCLE INTEGER,
    PROMO_DURATION_MONTHS INTEGER,
    FIRST_BILL_FLAG BOOLEAN
);

CREATE OR REPLACE TABLE BILLING_SYSTEM_DATA (
    BILLING_ID VARCHAR(25) PRIMARY KEY,
    CUSTOMER_ID VARCHAR(15),
    BILLING_DATE DATE,
    PRODUCT_ID VARCHAR(20),
    PROMO_CODE VARCHAR(30),
    BASE_AMOUNT DECIMAL(10,2),
    DISCOUNT_AMOUNT DECIMAL(10,2),
    FINAL_AMOUNT DECIMAL(10,2),
    BILLING_CYCLE VARCHAR(10),
    BILLING_CYCLE_NUMBER INTEGER,
    LINE_NUMBER VARCHAR(20),
    ACCOUNT_ID VARCHAR(25),
    PROMO_APPLIED_CYCLE INTEGER,
    PROMO_DURATION_MONTHS INTEGER
);

