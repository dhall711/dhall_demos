-- 4) Views and enrichment
-- Promotion reconciliation view with geo columns
CREATE OR REPLACE VIEW PROMOTION_RECONCILIATION AS
SELECT 
    COALESCE(o.ORDER_ID, 'MISSING-' || b.BILLING_ID) AS RECORD_ID,
    COALESCE(o.CUSTOMER_ID, b.CUSTOMER_ID) AS CUSTOMER_ID,
    COALESCE(o.ORDER_DATE, b.BILLING_DATE) AS TRANSACTION_DATE,
    COALESCE(o.PRODUCT_ID, b.PRODUCT_ID) AS PRODUCT_ID,
    p.PRODUCT_NAME,
    p.PRODUCT_CATEGORY,
    COALESCE(o.PROMO_CODE, b.PROMO_CODE) AS PROMO_CODE,
    pt.PROMO_NAME,
    -- Order amounts
    o.BASE_AMOUNT AS ORDER_BASE_AMOUNT,
    o.DISCOUNT_AMOUNT AS ORDER_DISCOUNT_AMOUNT,
    o.FINAL_AMOUNT AS ORDER_FINAL_AMOUNT,
    -- Billing amounts
    b.BASE_AMOUNT AS BILLING_BASE_AMOUNT,
    b.DISCOUNT_AMOUNT AS BILLING_DISCOUNT_AMOUNT,
    b.FINAL_AMOUNT AS BILLING_FINAL_AMOUNT,
    -- Variances
    COALESCE(o.DISCOUNT_AMOUNT,0) - COALESCE(b.DISCOUNT_AMOUNT,0) AS DISCOUNT_VARIANCE,
    COALESCE(o.FINAL_AMOUNT,0) - COALESCE(b.FINAL_AMOUNT,0) AS FINAL_AMOUNT_VARIANCE,
    ABS(COALESCE(o.DISCOUNT_AMOUNT,0) - COALESCE(b.DISCOUNT_AMOUNT,0)) AS ABS_VARIANCE,
    -- Status (enhanced for Fabio's use cases)
    CASE 
      WHEN o.ORDER_ID IS NULL THEN 'BILLING_ONLY'
      WHEN b.BILLING_ID IS NULL THEN 'ORDER_ONLY'
      WHEN b.PROMO_APPLIED_CYCLE != o.PROMO_START_CYCLE THEN 'PROMO_TIMING_MISMATCH'
      WHEN o.LINE_NUMBER IS NOT NULL AND EXISTS (
          SELECT 1 FROM ORDER_SYSTEM_DATA o2 
          WHERE o2.LINE_NUMBER = o.LINE_NUMBER AND o2.ORDER_ID != o.ORDER_ID
      ) THEN 'DUPLICATE_LINE_NUMBER'
      WHEN ABS(COALESCE(o.DISCOUNT_AMOUNT,0) - COALESCE(b.DISCOUNT_AMOUNT,0)) > 0.01 THEN 'DISCOUNT_MISMATCH'
      WHEN ABS(COALESCE(o.FINAL_AMOUNT,0) - COALESCE(b.FINAL_AMOUNT,0)) > 0.01 THEN 'AMOUNT_MISMATCH'
      ELSE 'MATCHED'
    END AS RECONCILIATION_STATUS,
    -- Risk (enhanced for Fabio's priority cases)
    CASE 
      WHEN o.ORDER_ID IS NULL OR b.BILLING_ID IS NULL THEN 'HIGH'
      WHEN o.FIRST_BILL_FLAG = TRUE AND b.BILLING_CYCLE_NUMBER != 1 THEN 'HIGH'  -- First bill issues are critical
      WHEN b.PROMO_APPLIED_CYCLE != o.PROMO_START_CYCLE THEN 'HIGH'  -- Timing issues
      WHEN o.LINE_NUMBER IS NOT NULL AND EXISTS (
          SELECT 1 FROM ORDER_SYSTEM_DATA o2 
          WHERE o2.LINE_NUMBER = o.LINE_NUMBER AND o2.ORDER_ID != o.ORDER_ID
      ) THEN 'HIGH'  -- Duplicate line numbers
      WHEN ABS(COALESCE(o.DISCOUNT_AMOUNT,0) - COALESCE(b.DISCOUNT_AMOUNT,0)) > 20 THEN 'HIGH'
      WHEN ABS(COALESCE(o.DISCOUNT_AMOUNT,0) - COALESCE(b.DISCOUNT_AMOUNT,0)) > 5 THEN 'MEDIUM'
      ELSE 'LOW'
    END AS RISK_LEVEL,
    -- Geo enrichment from customers
    c.SERVICE_CITY,
    c.SERVICE_STATE,
    c.SERVICE_REGION,
    c.CUSTOMER_LAT,
    c.CUSTOMER_LON
FROM ORDER_SYSTEM_DATA o
FULL OUTER JOIN BILLING_SYSTEM_DATA b ON o.ORDER_ID = REPLACE(b.BILLING_ID, 'BILL-', '')
LEFT JOIN PRODUCTS p ON COALESCE(o.PRODUCT_ID, b.PRODUCT_ID) = p.PRODUCT_ID
LEFT JOIN PROMOTION_TYPES pt ON COALESCE(o.PROMO_CODE, b.PROMO_CODE) = pt.PROMO_CODE
LEFT JOIN CUSTOMERS c ON COALESCE(o.CUSTOMER_ID, b.CUSTOMER_ID) = c.CUSTOMER_ID;

-- Summary view
CREATE OR REPLACE VIEW RECONCILIATION_SUMMARY AS
SELECT 
    'SUMMARY' AS DUMMY_KEY,
    COUNT(*) AS TOTAL_RECORDS,
    SUM(CASE WHEN RECONCILIATION_STATUS = 'MATCHED' THEN 1 ELSE 0 END) AS MATCHED_RECORDS,
    SUM(CASE WHEN RECONCILIATION_STATUS <> 'MATCHED' THEN 1 ELSE 0 END) AS EXCEPTION_RECORDS,
    ROUND(SUM(CASE WHEN RECONCILIATION_STATUS = 'MATCHED' THEN 1 ELSE 0 END) * 100.0 / NULLIF(COUNT(*),0), 2) AS MATCH_RATE_PCT,
    SUM(ABS(DISCOUNT_VARIANCE)) AS TOTAL_DISCOUNT_VARIANCE,
    SUM(ABS(FINAL_AMOUNT_VARIANCE)) AS TOTAL_AMOUNT_VARIANCE,
    SUM(CASE WHEN RISK_LEVEL = 'HIGH' THEN 1 ELSE 0 END) AS HIGH_RISK_COUNT,
    SUM(CASE WHEN RISK_LEVEL = 'MEDIUM' THEN 1 ELSE 0 END) AS MEDIUM_RISK_COUNT,
    SUM(CASE WHEN RISK_LEVEL = 'LOW' THEN 1 ELSE 0 END) AS LOW_RISK_COUNT
FROM PROMOTION_RECONCILIATION;

-- 5) Data validation queries (reference examples)
-- Count checks
SELECT 'ROW_COUNTS' AS CHECK_TYPE,
       (SELECT COUNT(*) FROM PRODUCTS) AS PRODUCTS,
       (SELECT COUNT(*) FROM PROMOTION_TYPES) AS PROMOTION_TYPES,
       (SELECT COUNT(*) FROM CUSTOMERS) AS CUSTOMERS,
       (SELECT COUNT(*) FROM ORDER_SYSTEM_DATA) AS ORDERS,
       (SELECT COUNT(*) FROM BILLING_SYSTEM_DATA) AS BILLING,
       (SELECT COUNT(*) FROM PROMOTION_RECONCILIATION) AS RECONCILIATION;

-- Referential integrity (orders -> products)
SELECT 'ORDERS_MISSING_PRODUCTS' AS CHECK_TYPE, COUNT(*) AS MISSING
FROM ORDER_SYSTEM_DATA o
LEFT JOIN PRODUCTS p ON o.PRODUCT_ID = p.PRODUCT_ID
WHERE p.PRODUCT_ID IS NULL;

-- Billing missing orders (intended ~5%)
SELECT 'BILLING_ONLY_RATE' AS CHECK_TYPE,
       SUM(CASE WHEN o.ORDER_ID IS NULL THEN 1 ELSE 0 END) * 100.0 / NULLIF(COUNT(*),0) AS PCT_BILLING_ONLY
FROM BILLING_SYSTEM_DATA b
LEFT JOIN ORDER_SYSTEM_DATA o ON o.ORDER_ID = REPLACE(b.BILLING_ID, 'BILL-', '');

-- Risk distribution sanity
SELECT 'RISK_DISTRIBUTION' AS CHECK_TYPE, RISK_LEVEL, COUNT(*) AS CNT, AVG(ABS(DISCOUNT_VARIANCE)) AS AVG_ABS_VAR
FROM PROMOTION_RECONCILIATION
GROUP BY RISK_LEVEL
ORDER BY CNT DESC;

