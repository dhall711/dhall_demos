        WHEN UNIFORM(1,100,RANDOM()) <= 95 THEN ROUND(DISCOUNT_AMOUNT * 2, 2)  -- Double billing error
        ELSE ROUND(DISCOUNT_AMOUNT + UNIFORM(10,50,RANDOM()), 2)  -- Additional incorrect charges
    END AS DISCOUNT_AMOUNT,
    0 AS FINAL_AMOUNT,
    'MONTHLY' AS BILLING_CYCLE,
    CASE 
        WHEN UNIFORM(1,100,RANDOM()) <= 95 THEN 1  -- First bill cycle
        WHEN UNIFORM(1,100,RANDOM()) <= 10 THEN 2  -- Promo applied late to second bill  
        ELSE 1
    END AS BILLING_CYCLE_NUMBER,
    CASE 
        WHEN LINE_NUMBER IS NOT NULL AND UNIFORM(1,100,RANDOM()) <= 8 THEN 
            -- 8% chance of duplicate line number issue - realistic scenarios
